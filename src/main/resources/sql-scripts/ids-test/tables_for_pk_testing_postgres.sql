-- DEFAULT: `table-name_pkey` is the default name for the primary key constraint.
CREATE TABLE plain_table (
    id   integer PRIMARY KEY,
    name text
);

-- With a name for the primary key
CREATE TABLE plain_named_pk_table(
    id   integer,
    name text,
    CONSTRAINT custom_pk_for_simple_table PRIMARY KEY (id)
);

-- Uuid
CREATE TABLE uuid_table (
     id   uuid PRIMARY KEY,
     name text
);

-- Two keys
CREATE TABLE two_keys_table (
    id1   integer,
    id2   integer,
    title varchar(20),
    PRIMARY KEY (id1, id2)
);

