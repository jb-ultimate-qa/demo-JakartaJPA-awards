-- SERIAL: PostgreSQL will generate a unique integer (1, 2, 3, and so on)
-- when you insert a new row into the table without providing the value for the order_id column.
CREATE TABLE serial_id_table (
    serial_id   SERIAL PRIMARY KEY,
    description VARCHAR(255)
);
-- smallserial and bigserial
CREATE TABLE serial_small_id_table (
    serial_id   SMALLSERIAL PRIMARY KEY,
    description VARCHAR(255)
);
CREATE TABLE serial_big_id_table (
    serial_id   BIGSERIAL PRIMARY KEY,
    description VARCHAR(255)
);

-- SEQUENCE
CREATE SEQUENCE int_sequence_for_id AS integer
--     start 2 increment 2
;
CREATE TABLE seq_id_table (
    seq_id integer NOT NULL DEFAULT nextval('int_sequence_for_id'),
    description VARCHAR(255),
    PRIMARY KEY (seq_id)
);
ALTER SEQUENCE int_sequence_for_id OWNED BY seq_id_table.seq_id;

-- IDENTITY
CREATE TABLE identity_gen_id_table (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    description VARCHAR(255)
);